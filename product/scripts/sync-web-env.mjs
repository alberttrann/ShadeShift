import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const rootEnvPath = resolve(process.cwd(), ".env");
const webDir = resolve(process.cwd(), "apps/web");
const webEnvPath = resolve(webDir, ".env.local");

const allowed = new Set([
  "NEXT_PUBLIC_API_BASE_URL",
  "NEXT_PUBLIC_MAPTILER_API_KEY",
]);

function parseEnv(text) {
  const result = new Map();

  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;

    const eq = line.indexOf("=");
    if (eq <= 0) continue;

    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    result.set(key, value);
  }

  return result;
}

if (!existsSync(rootEnvPath)) {
  console.warn(
    "[env] root .env not found; apps/web/.env.local left unchanged",
  );
  process.exit(0);
}

const source = parseEnv(readFileSync(rootEnvPath, "utf8"));

const lines = [
  "# AUTO-GENERATED by scripts/sync-web-env.mjs",
  "# Do not commit. Edit product/.env instead.",
  "",
];

const synced = [];
const missing = [];

for (const key of allowed) {
  const value = source.get(key) ?? "";
  lines.push(`${key}=${value}`);
  if (value) synced.push(key);
  else missing.push(key);
}

mkdirSync(webDir, { recursive: true });
writeFileSync(webEnvPath, `${lines.join("\n")}\n`, "utf8");

console.log(
  `[env] synced frontend variables to apps/web/.env.local: ${
    synced.length ? synced.join(", ") : "none"
  }`,
);

if (missing.includes("NEXT_PUBLIC_MAPTILER_API_KEY")) {
  console.log(
    "[env] MapTiler key is not configured; web will use local analysis view",
  );
} else {
  console.log(
    "[env] MapTiler key detected (value intentionally hidden)",
  );
}
